/**
 * Смена погоды по тексту ответа рассказчика, без запроса к модели.
 * Ищет в повествовании фразы вроде «пошёл дождь», «хлынул ливень», «дождь стих», «опустился туман»
 * и возвращает вид погоды, на который она сменилась (последнее событие в тексте побеждает).
 * Реплики героев (в кавычках и строки с тире) не считаются: там про погоду говорят, а не происходит.
 */
import { KIND_IDS } from './weather.js';

const W = '[\\p{L}\\-]*';                       // слово (с дефисом)
// каждая запись: вид погоды и набор выражений; порядок внутри списка значения не имеет
const RULES = [
  // прекращение и прояснение (проверяются вместе с остальными, побеждает самое позднее в тексте)
  { kind: 'clear', re: [
    `дожд${W}\\s+(?:вдруг\\s+|быстро\\s+|наконец\\s+)?(?:прекратил${W}|кончил${W}|закончил${W}|стих${W}|утих${W}|перестал${W}|иссяк${W})`,
    `(?:ливень|гроза|снегопад|метель|туман|ветер|буря)\\s+(?:вдруг\\s+|быстро\\s+|наконец\\s+)?(?:прекратил${W}|кончил${W}|закончил${W}|стих${W}|утих${W}|перестал${W}|рассеял${W}|развеял${W})`,
    `выглянул${W}\\s+(?:\\p{L}+\\s+){0,2}солнц${W}`,
    `небо\\s+(?:вдруг\\s+|быстро\\s+)?(?:прояснил${W}|расчистил${W}|развиднел${W})`,
    `тучи\\s+(?:разошл${W}|рассеял${W}|разбежал${W})`,
    `развиднел${W}`, `перестал${W}\\s+(?:дождь|снег|идти)`,
  ] },
  { kind: 'rain', re: [
    `(?:пошёл|пошел|начал${W}|хлынул${W}|полил${W}|припустил${W}|закапал${W}|заморосил${W}|забарабанил${W}|обрушил${W})\\s+(?:\\p{L}+\\s+){0,2}(?:дождь|дождик|ливень|ливни)`,
    `(?:дождь|дождик|ливень)\\s+(?:вдруг\\s+)?(?:пошёл|пошел|начал${W}|хлынул${W}|полил${W}|припустил${W}|забарабанил${W}|усилил${W})`,
    `(?:заморосил${W}|закапал${W}|заморосило|закапало|накрапывать|накрапывает|накрапывал${W})`,
    `(?:небо|тучи)\\s+(?:\\p{L}+\\s+){0,2}(?:разразил${W}|разверз${W})\\s+(?:\\p{L}+\\s+){0,2}ливн${W}`,
  ] },
  { kind: 'storm', re: [
    `(?:грянул|ударил|раскатил${W}|прогремел${W}|сверкнул${W}|полыхнул${W}|разразил${W})\\s+(?:\\p{L}+\\s+){0,2}(?:гром|молни${W}|гроза|грозой)`,
    `(?:гроза|буря|шторм)\\s+(?:разразил${W}|надвинул${W}|налетел${W}|разыграл${W}|началась)`,
    `(?:начал${W}|разразил${W})\\s+(?:\\p{L}+\\s+){0,2}(?:гроза|буря|шторм)`,
  ] },
  { kind: 'snow', re: [
    `(?:пошёл|пошел|повалил${W}|закружил${W}|посыпал${W}|начал${W}|запорошил${W})\\s+(?:\\p{L}+\\s+){0,2}(?:снег|снежинк${W}|снегопад|метель|хлопья)`,
    `(?:снег|снегопад|метель)\\s+(?:вдруг\\s+)?(?:пошёл|пошел|начал${W}|повалил${W}|поднял${W}|усилил${W})`,
    `закружил${W}\\s+(?:\\p{L}+\\s+){0,2}снежинк${W}`,
  ] },
  { kind: 'fog', re: [
    `(?:опустил${W}|поднял${W}|сгустил${W}|надвинул${W}|стелил${W}|наполз${W})\\s+(?:\\p{L}+\\s+){0,2}туман`,
    `туман\\s+(?:вдруг\\s+)?(?:опустил${W}|поднял${W}|сгустил${W}|окутал${W}|накрыл${W}|наполз${W}|заволок${W}|стлал${W})`,
  ] },
  { kind: 'wind', re: [
    `(?:поднял${W}|налетел${W}|задул${W}|завыл${W}|взвыл${W}|разыграл${W}|усилил${W})\\s+(?:\\p{L}+\\s+){0,2}(?:ветер|ветр${W}|буран)`,
    `ветер\\s+(?:вдруг\\s+)?(?:поднял${W}|налетел${W}|задул${W}|усилил${W}|завыл${W}|взвыл${W}|рванул${W}|окреп${W})`,
  ] },
  { kind: 'cloudy', re: [
    `(?:небо|солнце)\\s+(?:вдруг\\s+)?(?:затянул${W}|нахмурил${W}|потемнел${W}|заволокл${W}|скрыл${W}\\s+за\\s+туч)`,
    `(?:набежал${W}|нахлынул${W}|собрал${W}|затянул${W})\\s+(?:\\p{L}+\\s+){0,2}тучи`,
    `тучи\\s+(?:сгустил${W}|затянул${W}|нависл${W}|набежал${W}|собрал${W})`,
  ] },
];

// слова, после которых «пошёл дождь» не событие, а условие или отрицание
const NEGATION = /(?:^|[^\p{L}])(?:не|если|когда|вдруг\s+не|будто|словно|как\s+будто|чтобы|пока\s+не|ни|бы|хоть)\s*$/u;

/** Убирает речь героев: фразы в кавычках и строки, начинающиеся с тире. */
export function narrationOnly(text) {
  return String(text ?? '')
    .split(/\r?\n/)
    .filter(line => !/^\s*[—–-]\s/.test(line))
    .join('\n')
    .replace(/«[^»]*»/g, ' ')
    .replace(/“[^”]*”/g, ' ')
    .replace(/"[^"\n]*"/g, ' ');
}

/** Возвращает { kind, phrase } для самой поздней смены погоды в тексте или null. */
export function detectWeatherChange(text) {
  const source = narrationOnly(text).toLowerCase().replace(/ё/g, 'е');
  let best = null;
  for (const rule of RULES) {
    for (const pattern of rule.re) {
      const re = new RegExp(pattern.replace(/ё/g, 'е'), 'giu');
      for (const match of source.matchAll(re)) {
        const before = source.slice(Math.max(0, match.index - 18), match.index);
        if (NEGATION.test(before)) continue;
        if (!best || match.index >= best.index) best = { kind: rule.kind, phrase: match[0], index: match.index };
      }
    }
  }
  return best && KIND_IDS.includes(best.kind) ? { kind: best.kind, phrase: best.phrase } : null;
}
