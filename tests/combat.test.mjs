import test from 'node:test';
import assert from 'node:assert/strict';
import { detectCombat, detectTension } from '../src/core/tension.js';
import { detectAutoMode } from '../src/core/fate.js';

test('бой включают конкретные действия, ведущие к бою', () => {
  for (const text of [
    'Он обнажил меч и шагнул вперёд.', 'Гоблины напали из темноты.', 'Стражник выхватил кинжал.', 'Началась схватка у ворот.', 'Начался бой.',
    'Они угодили в засаду.', 'Разбойник бросился в атаку.', 'Орк рубанул топором.', 'Лучница выпустила стрелу в сторону лагеря.', 'Из засады вышли двое.',
    'Он вскочил, выхватил оружие и закричал.', 'Тифлинг нанёс удар кинжалом.', 'Враг атаковал первым.',
  ]) assert.equal(detectCombat(text), true, text);
});

test('крики, пожар, угрозы, «смертельно» и бытовые действия бой не включают', () => {
  for (const text of [
    'Крики торговцев разносились над лагерем гоблинов.', 'Где-то вспыхнул пожар, но его быстро потушили.', 'Над лагерем стояла паника и тревога.',
    'Смертельно опасный яд лежал на прилавке.', 'Он накинул плащ и подошёл к торговцу.', 'Торговец достал нож и нарезал хлеб.',
    'Она бросилась на шею старому другу.', 'Гоблин зарычал от смеха.', 'Она убила время у костра.', 'Звон монет не смолкал.',
    '— Я обнажил меч! — крикнул он.', 'Он не обнажил меч, а убрал руки за спину.', 'Если они нападут, мы побежим.', 'Погоня закончилась ничем, все смеялись.',
  ]) assert.equal(detectCombat(text), false, text);
});

test('напряжение по тем же словам растёт отдельно: крик поднимает его, но бой не включается', () => {
  const t = detectTension('Над лагерем раздались крики и поднялась паника.');
  assert.ok(t?.kind === 'up' && t.level >= 3);                                // шкала напряжения показывает «тревожно»
  assert.equal(detectCombat('Над лагерем раздались крики и поднялась паника.'), false);
  // режим сцены: высокое напряжение само по себе боя не даёт, боевое действие даёт
  assert.equal(detectAutoMode({ text: 'Крики.', level: 4, combat: false, mode: 'camp', auto: true, place: 'Лагерь' }), null);
  const r = detectAutoMode({ text: 'Гоблины напали.', level: 4, combat: true, mode: 'camp', auto: false, place: 'Лагерь гоблинов' });
  assert.equal(r.mode, 'fight'); assert.equal(r.auto, true); assert.deepEqual(r.back, { mode: 'camp', auto: false });   // прежний режим запомнен
});
